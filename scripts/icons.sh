#!/usr/bin/env bash
# Renders the browser and phone icons from the layers of the Mac app icon,
# apple/CmdPalm/AppIcon.icon, so every icon shares one design. Xcode compiles
# the Mac icon itself. Needs rsvg-convert (brew install librsvg) and bun.
# Outputs are committed, so this only runs when the artwork changes.
set -euo pipefail
cd "$(dirname "$0")/.."

layers=apple/CmdPalm/AppIcon.icon/Assets
for tool in rsvg-convert bun; do
  command -v "$tool" >/dev/null || {
    echo "error: $tool is required to regenerate icons (see CONTRIBUTING.md)" >&2
    exit 1
  }
done
mkdir -p web/public build

scratch=$(mktemp -d build/icons.XXXXXX)
trap 'rm -rf "$scratch"' EXIT

# Icon Composer adds the background, glass and shadows to the flat layers;
# the web icon adds its own gradients and shadows to the same shapes.
cat >"$scratch/compose.ts" <<'TS'
const [dir, rounded, square] = process.argv.slice(2) as [string, string, string]

async function layer(name: string, fills: Record<string, string> = {}): Promise<string> {
  const svg = await Bun.file(`${dir}/${name}`).text()
  if (!/viewBox="0 0 512 512"/.test(svg)) throw new Error(`${name} must use viewBox="0 0 512 512"`)
  let body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim()
  for (const [color, fill] of Object.entries(fills)) {
    if (!body.includes(`fill="${color}"`)) throw new Error(`${name} has no fill="${color}" for the web icon to restyle`)
    body = body.replaceAll(`fill="${color}"`, `fill="${fill}"`)
  }
  return body
}

const phone = '#FFF5E4'
const parts = {
  edge: await layer('01-phone.svg', { [phone]: '#EFD0A6' }),
  phone: await layer('01-phone.svg', { [phone]: 'url(#surface)' }),
  details: await layer('04-phone-details.svg'),
  command: await layer('02-command.svg', { '#C54B25': 'url(#command)' }),
  touch: await layer('03-touch.svg', { '#F9813D': 'url(#touch)' }),
}

const icon = (radius: number) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" fill="none">
  <title>CmdPalm</title>
  <desc>A Command key on a touch surface, with a fingertip contact at its upper corner.</desc>
  <!-- Generated by scripts/icons.sh from apple/CmdPalm/AppIcon.icon. -->
  <defs>
    <linearGradient id="background" x1="64" y1="0" x2="464" y2="512" gradientUnits="userSpaceOnUse">
      <stop stop-color="#FFB45F"/>
      <stop offset="0.48" stop-color="#F9813D"/>
      <stop offset="1" stop-color="#CF4F28"/>
    </linearGradient>
    <radialGradient id="light" cx="0" cy="0" r="1" gradientTransform="translate(148 82) rotate(52) scale(394 360)" gradientUnits="userSpaceOnUse">
      <stop stop-color="#FFE0A9" stop-opacity="0.55"/>
      <stop offset="1" stop-color="#FFE0A9" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="surface" x1="163" y1="118" x2="344" y2="410" gradientUnits="userSpaceOnUse">
      <stop stop-color="#FFFEF8"/>
      <stop offset="0.6" stop-color="#FFF3DF"/>
      <stop offset="1" stop-color="#F2D4AD"/>
    </linearGradient>
    <linearGradient id="command" x1="0" y1="0" x2="1" y2="1">
      <stop stop-color="#DA6733"/>
      <stop offset="1" stop-color="#BA3F20"/>
    </linearGradient>
    <linearGradient id="touch" x1="333" y1="114" x2="375" y2="158" gradientUnits="userSpaceOnUse">
      <stop stop-color="#FFAA55"/>
      <stop offset="1" stop-color="#EC682E"/>
    </linearGradient>
    <filter id="lift" x="72" y="50" width="376" height="446" filterUnits="userSpaceOnUse" color-interpolation-filters="sRGB">
      <feDropShadow dx="0" dy="18" stdDeviation="14" flood-color="#762B1B" flood-opacity="0.24"/>
      <feDropShadow dx="0" dy="3" stdDeviation="2" flood-color="#A94425" flood-opacity="0.2"/>
    </filter>
    <filter id="contact" x="293" y="79" width="119" height="120" filterUnits="userSpaceOnUse" color-interpolation-filters="sRGB">
      <feDropShadow dx="0" dy="5" stdDeviation="4" flood-color="#A43C1F" flood-opacity="0.2"/>
    </filter>
  </defs>
  <rect width="512" height="512"${radius ? ` rx="${radius}"` : ''} fill="url(#background)"/>
  <rect width="512" height="512"${radius ? ` rx="${radius}"` : ''} fill="url(#light)"/>
  ${radius ? `<rect x="1" y="1" width="510" height="510" rx="${radius - 1}" stroke="#FFF1D7" stroke-opacity="0.17" stroke-width="2"/>` : ''}
  <g filter="url(#lift)">
    <g transform="translate(0 4)">${parts.edge}</g>
    ${parts.phone}
    ${parts.details}
    ${parts.command}
  </g>
  <g filter="url(#contact)">${parts.touch}</g>
</svg>
`

// The browser shows the rounded icon; phone home screens apply their own mask.
await Bun.write(rounded, icon(114))
await Bun.write(square, icon(0))
TS
bun "$scratch/compose.ts" "$layers" web/public/icon.svg "$scratch/icon-square.svg"

render() { rsvg-convert -w "$2" -h "$2" "$1" -o "$3"; }

render "$scratch/icon-square.svg" 180 web/public/apple-touch-icon.png
render "$scratch/icon-square.svg" 192 web/public/icon-192.png
render "$scratch/icon-square.svg" 512 web/public/icon-512.png
echo "Icons updated."
