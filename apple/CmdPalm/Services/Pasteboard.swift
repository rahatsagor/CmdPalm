import AppKit
import Synchronization

/// Clipboard access for the phone, and the save/restore around a paste.
final class Pasteboard: Sendable {
    private struct Saved: @unchecked Sendable {
        let items: [[NSPasteboard.PasteboardType: Data]]
        let changeCount: Int
    }

    /// Marks our temporary clipboard contents so clipboard managers skip them
    /// (http://nspasteboard.org).
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let generated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")

    private struct State: Sendable {
        /// The user's clipboard from before the first outstanding paste.
        var saved: Saved?
        /// Pastes begun but not yet ended; only the last end restores.
        var depth = 0
    }

    private let state = Mutex(State())

    func text() -> String? {
        NSPasteboard.general.string(forType: .string)
    }

    func setText(_ text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
    }

    func beginPaste(_ text: String) -> Bool {
        state.withLock { state in
            let board = NSPasteboard.general
            let current = Self.snapshot(board)
            // During an overlapping paste the board holds the earlier pasted
            // text, so keep the earlier snapshot unless someone copied since.
            let original = state.saved.flatMap { $0.changeCount == board.changeCount ? $0.items : nil } ?? current
            board.clearContents()
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            item.setData(Data(), forType: Self.transient)
            item.setData(Data(), forType: Self.generated)
            item.setString(Bundle.main.bundleIdentifier ?? "app.cmdpalm.mac", forType: Self.source)
            guard board.writeObjects([item]) else {
                Self.restore(current, to: board)
                if state.saved != nil {
                    state.saved = Saved(items: original, changeCount: board.changeCount)
                }
                return false
            }
            state.saved = Saved(items: original, changeCount: board.changeCount)
            state.depth += 1
            return true
        }
    }

    func endPaste() {
        state.withLock { state in
            guard state.depth > 0 else { return }
            state.depth -= 1
            guard state.depth == 0, let saved = state.saved else { return }
            state.saved = nil
            let board = NSPasteboard.general
            // Something else copied in the meantime; keep that instead.
            guard board.changeCount == saved.changeCount else { return }
            Self.restore(saved.items, to: board)
        }
    }

    private static func snapshot(_ board: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (board.pasteboardItems ?? []).map { item in
            var copy: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { copy[type] = data }
            }
            return copy
        }
    }

    private static func restore(_ contents: [[NSPasteboard.PasteboardType: Data]], to board: NSPasteboard) {
        board.clearContents()
        let items = contents.map { contents in
            let item = NSPasteboardItem()
            for (type, data) in contents { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { board.writeObjects(items) }
    }
}
